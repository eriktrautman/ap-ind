#!/usr/bin/env python3
"""
Turn the crawler's raw images + manifest into the served photo set and config/photos.json.

  public/photos/congress/<apid>.jpg   public-domain official portraits (gitignored, regenerable)
  public/photos/bp/<apid>.jpg         Ballotpedia-sourced (gitignored; fair use for identification)
  config/photos.json                  manifest: id -> {file, source, confidence, url, page, license}
  <work-dir>/sheets/<state>.jpg       contact sheets for the human pass

Candidates already in config/candidates.json keep their hand-verified photo and are not overwritten.
Usage: python3 -I scripts/build-photo-index.py <work-dir>
"""
import json, os, sys
from PIL import Image, ImageDraw

WORK = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAXH = 600

manifest = json.load(open(f"{WORK}/manifest.json"))
todo = {c["id"]: c for c in json.load(open(f"{WORK}/candidates-todo.json"))}
curated = {c["id"]: c for c in json.load(open(f"{ROOT}/config/candidates.json"))["candidates"]}
out = {}
for sub in ("congress", "bp"):
    os.makedirs(f"{ROOT}/public/photos/{sub}", exist_ok=True)

for cid, m in manifest.items():
    c = todo.get(cid)
    if not c:
        continue
    cur = curated.get(cid)
    if cur and cur.get("photo") and (cur["photo"].get("file") or cur["photo"].get("remote")):
        p = cur["photo"]
        out[cid] = {"file": f"/photos/{p['file']}" if p.get("file") else None, "remote": p.get("remote"), "source": "curated", "confidence": "verified",
                    "license": p.get("license"), "page": p.get("page"), "name": c["name"], "race": c["race"], "party": c["party"], "featured": c["featured"]}
        continue
    base = {"name": c["name"], "race": c["race"], "party": c["party"], "featured": c["featured"], "source": m.get("source"), "confidence": m.get("confidence"),
            "url": m.get("url"), "page": m.get("page"), "license": m.get("license"), "credit": m.get("credit"), "note": m.get("note"), "file": None}
    src = None
    for ext in (".jpg", ".png"):
        if os.path.exists(f"{WORK}/raw/{cid}{ext}"):
            src = f"{WORK}/raw/{cid}{ext}"; break
    if src and m.get("source"):
        sub = "congress" if m["source"] == "congress" else "bp"
        try:
            im = Image.open(src); im.load(); im = im.convert("RGB")
            if im.height > MAXH:
                im = im.resize((round(im.width * MAXH / im.height), MAXH), Image.LANCZOS)
            im.save(f"{ROOT}/public/photos/{sub}/{cid}.jpg", quality=86, optimize=True)
            base["file"] = f"/photos/{sub}/{cid}.jpg"
            base["size"] = [im.width, im.height]
        except Exception as e:
            base["note"] = f"unreadable image: {e}"
    out[cid] = base

json.dump({"_comment": "Generated by scripts/build-photo-index.py. Keyed by AP candidateID. 'curated' entries are hand-verified (config/candidates.json); 'congress' are public-domain official portraits; 'bp' are Ballotpedia-sourced with an automatic confidence (high: name in filename and exact name match; medium: one of those; low: neither) and need a human check before air.",
           "generated": __import__("datetime").date.today().isoformat(), "photos": out}, open(f"{ROOT}/config/photos.json", "w"), indent=1)

# contact sheets by state for the human pass
os.makedirs(f"{WORK}/sheets", exist_ok=True)
by_state = {}
for cid, e in out.items():
    by_state.setdefault(e["race"][:2], []).append((cid, e))
TH, TW, COLS = 150, 120, 8
for st, items in sorted(by_state.items()):
    items.sort(key=lambda x: (x[1]["race"], not x[1]["featured"], x[1]["name"]))
    rows = (len(items) + COLS - 1) // COLS
    sheet = Image.new("RGB", (COLS * (TW + 10) + 10, rows * (TH + 48) + 10), (20, 25, 35))
    d = ImageDraw.Draw(sheet)
    for i, (cid, e) in enumerate(items):
        x = 10 + (i % COLS) * (TW + 10); y = 10 + (i // COLS) * (TH + 48)
        f = e.get("file")
        path = f"{ROOT}/public{f}" if f else None
        if path and os.path.exists(path):
            im = Image.open(path).convert("RGB"); im.thumbnail((TW, TH)); sheet.paste(im, (x + (TW - im.width) // 2, y))
        else:
            d.rectangle([x, y, x + TW, y + TH], outline=(90, 90, 90)); d.text((x + 8, y + TH // 2 - 6), "no photo", fill=(150, 150, 150))
        conf = e.get("confidence") or "-"
        col = {"verified": (120, 220, 140), "high": (200, 200, 200), "medium": (240, 190, 80), "low": (240, 90, 90)}.get(conf, (150, 150, 150))
        d.text((x, y + TH + 4), e["name"][:22], fill=(255, 255, 255))
        d.text((x, y + TH + 18), f"{e['race']} {e['party']}", fill=(170, 180, 200))
        d.text((x, y + TH + 32), f"{e['source'] or 'none'} · {conf}", fill=col)
    sheet.save(f"{WORK}/sheets/{st}.jpg", quality=85)

from collections import Counter
print("photos:", Counter(e["source"] for e in out.values()), "| confidence:", Counter(e.get("confidence") for e in out.values()))
