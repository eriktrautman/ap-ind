// Build step: writes dist/g/theme-boot.js, a tiny classic script every output page loads first thing in <head>, so the
// stylesheet is decided before the first paint and a page never flashes from the written-in colours to the live ones.
// It carries, generated from public/g/themes.js: the default stylesheet's id and every stylesheet's output variables
// (already mapped onto the graphics' and ticker's variable names). At load it applies, in this order: ?theme= on the
// address; the stylesheet this browser last saw published (themes.js keeps it in localStorage); the default. The module
// then confirms against the published state within a second and corrects the rare case where it changed since.
import { writeFile } from "node:fs/promises";
import { THEMES, DEFAULT_THEME, AIR_VARS } from "../../public/g/themes.js";

const out = process.argv[2] ?? new URL("../dist/g/theme-boot.js", import.meta.url).pathname;
const vars = {};
for (const [id, t] of Object.entries(THEMES)) {
  vars[id] = {};
  for (const [k, outs] of Object.entries(AIR_VARS)) { const v = t.tokens[k]; if (v) for (const o of outs) vars[id][o] = v; }
}
const fonts = Object.fromEntries(Object.entries(THEMES).filter(([, t]) => t.font).map(([id, t]) => [id, t.font]));
const js = `/* generated by scripts/theme-boot.mjs from public/g/themes.js; do not edit */
(function () { try {
  var D = ${JSON.stringify(DEFAULT_THEME)}, T = ${JSON.stringify(vars)}, F = ${JSON.stringify(fonts)}, ALL = ${JSON.stringify(Object.values(AIR_VARS).flat())};
  var q = new URLSearchParams(location.search).get("theme"), saved = null;
  try { saved = localStorage.getItem("ep.theme"); } catch (e) {}
  var id = q && T[q] ? q : saved && T[saved] ? saved : D;
  var r = document.documentElement, v = T[id] || {};
  for (var i = 0; i < ALL.length; i++) r.style.removeProperty(ALL[i]);
  for (var k in v) r.style.setProperty(k, v[k]);
  r.dataset.theme = id;
  if (F[id] && document.head) { var l = document.createElement("link"); l.id = "ep-theme-font"; l.rel = "stylesheet"; l.href = F[id]; document.head.appendChild(l); }
} catch (e) {} })();
`;
await writeFile(out, js);
console.log(`theme-boot.js: ${Object.keys(vars).length} stylesheets, default ${DEFAULT_THEME} → ${out}`);
